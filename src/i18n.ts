const dicts: Record<Lang, Dict> = { en, "zh-TW": zhTW };

export function translate(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let s = dicts[lang]?.[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{{${k}}}`, String(v));
    }
  }
  return s;
}

/** Localize a backend API error: prefer the stable `code`, fall back to
 * whatever English message the backend sent (never a raw i18n key). `vars`
 * (e.g. live daily-budget numbers) get interpolated into the localized
 * template so the sentence stays translated while the numbers stay live. */
export function apiErrorMessage(
  lang: Lang,
  err: { code?: string; error?: string; vars?: Record<string, string | number> } | undefined,
  fallbackKey: string,
): string {
  if (err?.code && dicts[lang]?.[`error.${err.code}`]) {
    return translate(lang, `error.${err.code}`, err.vars);
  }
  if (err?.error) return err.error;
  return translate(lang, fallbackKey);
}

export function defaultLang(): Lang {
  return "en";
}
